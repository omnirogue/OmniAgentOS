def git_rev_parse_head(repo_root: Path, *, runner: CommandRunner | None = None) -> str:
    """Return the full HEAD sha."""
    code, out = _run_git(["rev-parse", "HEAD"], repo_root, runner=runner)
    if code != 0:
        raise ReleaseGateError(f"git rev-parse HEAD failed (rc={code}): {out.strip()}")
    sha = out.strip()
    if len(sha) < 7:
        raise ReleaseGateError(f"git rev-parse HEAD returned unusable sha: {sha!r}")
    return sha


def git_is_dirty(repo_root: Path, *, runner: CommandRunner | None = None) -> bool:
    """True when the worktree has uncommitted or untracked changes."""
    code, out = _run_git(["status", "--porcelain"], repo_root, runner=runner)
    if code != 0:
        raise ReleaseGateError(f"git status --porcelain failed (rc={code}): {out.strip()}")
    return bool(out.strip())


def git_dirty_summary(repo_root: Path, *, runner: CommandRunner | None = None) -> str:
    """Short porcelain summary for refuse messages (capped)."""
    code, out = _run_git(["status", "--porcelain"], repo_root, runner=runner)
    if code != 0:
        return f"(git status failed rc={code})"
    lines = [ln for ln in out.splitlines() if ln.strip()]
    if not lines:
        return ""
    head = lines[:12]
    extra = len(lines) - len(head)
    body = "\n".join(head)
    if extra > 0:
        body += f"\n... and {extra} more"
    return body


def _run_git(
    args: Sequence[str],
    repo_root: Path,
    *,
    runner: CommandRunner | None = None,
) -> tuple[int, str]:
    argv = ["git", "-C", str(repo_root), *args]
    if runner is not None:
        return runner(argv, repo_root)
    return _default_runner(argv, repo_root)


def _default_runner(
    argv: Sequence[str],
    cwd: Path,
    env: Mapping[str, str] | None = None,
) -> tuple[int, str]:
    try:
        proc = subprocess.run(
            list(argv),
            cwd=str(cwd),
            capture_output=True,
            text=True,
            check=False,
            env=dict(env) if env is not None else None,
        )
    except FileNotFoundError as exc:
        return 127, f"command not found: {argv[0]} ({exc})"
    combined = (proc.stdout or "") + (proc.stderr or "")
    return int(proc.returncode), combined


def make_default_runner(env: Mapping[str, str] | None = None) -> CommandRunner:
    """Bind *env* to the default subprocess runner.

    Keeps the two-argument :data:`CommandRunner` contract that injected test
    runners rely on while letting the gate hand certification environment
    (notably ``OMNIAGENTOS_REQUIRE_PG=1``) to every phase subprocess.
    """
    bound = dict(env) if env is not None else None

    def _runner(argv: Sequence[str], cwd: Path) -> tuple[int, str]:
        return _default_runner(argv, cwd, env=bound)

    return _runner


def assert_clean_and_pinned(
    repo_root: Path,
    pinned_sha: str,
    *,
    allow_dirty: bool = False,
    runner: CommandRunner | None = None,
) -> str:
    """Refuse dirty or moved HEAD. Returns the verified current HEAD sha."""
    head = git_rev_parse_head(repo_root, runner=runner)
    if head != pinned_sha:
        raise MovingHeadError(f"HEAD moved during release gate: pinned={pinned_sha} current={head}")
    if not allow_dirty and git_is_dirty(repo_root, runner=runner):
        summary = git_dirty_summary(repo_root, runner=runner)
        raise DirtyTreeError(
            "worktree is dirty — release gate refuses certification on a "
            f"moving/dirty tree at {pinned_sha}:\n{summary}"
        )
    return head


def select_phases(
    specs: Sequence[PhaseSpec],
    *,
    only: Sequence[str] | None = None,
    env: Mapping[str, str] | None = None,  # noqa: ARG001 (kept for API symmetry)
) -> list[PhaseSpec]:
    """Filter phase specs by name list (None = all) and conditional env flags.

    Conditional phases default to *enabled* when their env var is unset so the
    full gate includes them. Set ``RELEASE_GATE_LIVE=0`` / ``RELEASE_GATE_LOAD=0``
    to skip with explicit evidence (not a silent drop from the plan).

    Note: The *env* parameter is accepted for API symmetry with phase_should_run
    but phase selection itself does not depend on environment variables.
    """
    wanted: set[str] | None
    if only is None:
        wanted = None
    else:
        wanted = {n.strip() for n in only if n.strip()}
        unknown = wanted - {s.name for s in specs}
        if unknown:
            raise ReleaseGateError(f"unknown phase name(s): {sorted(unknown)}")

    selected: list[PhaseSpec] = []
    for spec in specs:
        if wanted is not None and spec.name not in wanted:
            continue
        selected.append(spec)
    # Preserve canonical order
    order = {name: i for i, name in enumerate(ALL_PHASE_NAMES)}
    selected.sort(key=lambda s: order.get(s.name, 999))
    return selected


def phase_should_run(spec: PhaseSpec, env: Mapping[str, str] | None = None) -> bool:
    """Whether a (possibly conditional) phase should execute."""
    if not spec.conditional:
        return True
    e = env if env is not None else os.environ
    key = spec.enable_env or ""
    if not key:
        return True
    raw = e.get(key)
    if raw is None:
        # Default ON for full-gate certification.
        return True
    return _truthy(raw)


def run_phase(
    spec: PhaseSpec,
    *,
    repo_root: Path,
    pinned_sha: str,
    allow_dirty: bool,
    dry_run: bool = False,
    env: Mapping[str, str] | None = None,
    runner: CommandRunner | None = None,
) -> PhaseEvidence:
    """Execute one phase under pinned-SHA / clean-tree enforcement."""
    started = _utc_now()
    t0 = time.monotonic()
    head_start = assert_clean_and_pinned(
        repo_root, pinned_sha, allow_dirty=allow_dirty, runner=runner
    )

    if dry_run:
        ended = _utc_now()
        return PhaseEvidence(
            name=spec.name,
            status="planned",
            pinned_sha=pinned_sha,
            head_sha_at_start=head_start,
            head_sha_at_end=head_start,
            started_at=started,
            ended_at=ended,
            duration_ms=int((time.monotonic() - t0) * 1000),
            exit_code=None,
            command=list(spec.argv),
            detail=spec.description,
        )

    if not phase_should_run(spec, env=env):
        ended = _utc_now()
        head_end = assert_clean_and_pinned(
            repo_root, pinned_sha, allow_dirty=allow_dirty, runner=runner
        )
        return PhaseEvidence(
            name=spec.name,
            status="skipped",
            pinned_sha=pinned_sha,
            head_sha_at_start=head_start,
            head_sha_at_end=head_end,
            started_at=started,
            ended_at=ended,
            duration_ms=int((time.monotonic() - t0) * 1000),
            exit_code=None,
            command=list(spec.argv),
            detail=(f"conditional phase disabled via {spec.enable_env}=0 ({spec.description})"),
        )

    # With no injected runner this is the layer that actually spawns the phase,
    # so this is where the certification environment must be applied — a caller
    # invoking run_phase directly must not get a subprocess that can skip its
    # PostgreSQL-backed tests into a false green.
    run = runner or make_default_runner(certification_env(env))
    code, output = run(spec.argv, repo_root)
    # Re-pin check after the phase — refuse if HEAD moved during the phase.
    try:
        head_end = assert_clean_and_pinned(
            repo_root, pinned_sha, allow_dirty=allow_dirty, runner=runner
        )
    except ReleaseGateError as exc:
        ended = _utc_now()
        return PhaseEvidence(
            name=spec.name,
            status="refused",
            pinned_sha=pinned_sha,
            head_sha_at_start=head_start,
            head_sha_at_end="",
            started_at=started,
            ended_at=ended,
            duration_ms=int((time.monotonic() - t0) * 1000),
            exit_code=code,
            command=list(spec.argv),
            detail=str(exc),
            log_excerpt=_excerpt(output),
        )

    ended = _utc_now()
    status: PhaseStatus = "passed" if code == 0 else "failed"
    return PhaseEvidence(
        name=spec.name,
        status=status,
        pinned_sha=pinned_sha,
        head_sha_at_start=head_start,
        head_sha_at_end=head_end,
        started_at=started,
        ended_at=ended,
        duration_ms=int((time.monotonic() - t0) * 1000),
        exit_code=code,
        command=list(spec.argv),
        detail=spec.description if code == 0 else f"phase failed with exit {code}",
        log_excerpt=_excerpt(output),
    )


def _excerpt(text: str, limit: int = 4000) -> str:
    text = text or ""
    if len(text) <= limit:
        return text
    return text[: limit - 20] + "\n...[truncated]..."


def write_evidence(evidence: GateEvidence, path: Path) -> Path:
    """Persist gate evidence as JSON, refusing to overwrite an existing record.

    Opened ``O_CREAT | O_EXCL`` rather than checked-then-written: two concurrent
    gate runs that generated the same candidate name would both pass an
    ``exists()`` test and the second would silently overwrite the first's audit
    trail. Exclusive creation makes the loser fail instead of destroying
    evidence, which is the whole point of the record.
    """
    path.parent.mkdir(parents=True, exist_ok=True)
    payload = json.dumps(evidence.to_dict(), indent=2, sort_keys=True) + "\n"
    fd = os.open(path, os.O_CREAT | os.O_EXCL | os.O_WRONLY, 0o644)
    with os.fdopen(fd, "w", encoding="utf-8") as handle:
        handle.write(payload)
    return path


def _evidence_stamp() -> str:
    """UTC stamp for evidence filenames (microsecond resolution)."""
    return datetime.now(UTC).strftime("%Y%m%dT%H%M%S%fZ")


def evidence_path_for(
    repo_root: Path, pinned_sha: str, env: Mapping[str, str] | None = None
) -> Path:
    """Default evidence location under the lane/runtime var dir.

    The filename must be unique even when two gate runs share a pinned SHA
    *and* start within the same clock tick — a second-resolution
    ``<stamp>-<sha>.json`` name silently overwrote the earlier run's evidence,
    destroying exactly the audit trail the gate exists to produce. Uniqueness
    comes from four independent sources: microsecond stamp, an in-process
    monotonic sequence, the pid (distinguishes concurrent processes), and a
    random suffix (survives pid reuse).

    This returns a *candidate*; it deliberately does not probe the filesystem,
    because a check here could not bind the later write anyway. Exclusivity is
    enforced where it is actually atomic, by :func:`write_evidence`.
    """
    e = env if env is not None else os.environ
    var = (e.get("OMNIAGENTOS_VAR_DIR") or e.get("OMNIAGENTOS_VAR") or "").strip()
    base = Path(var) if var else (repo_root / "var")
    short = pinned_sha[:12] if pinned_sha else "unknown"
    stamp = _evidence_stamp()
    seq = next(_EVIDENCE_SEQ)
    suffix = uuid.uuid4().hex[:8]
    return base / "release-gate" / f"{stamp}-{short}-p{os.getpid()}-s{seq}-{suffix}.json"


def certification_env(base: Mapping[str, str] | None = None) -> dict[str, str]:
    """Environment handed to phase subprocesses during certification."""
    env = dict(base if base is not None else os.environ)
    env[ENV_REQUIRE_PG] = "1"
    env.pop("PYTEST_ADDOPTS", None)
    return env


def run_release_gate(
    *,
    repo_root: Path | None = None,
    phases: Sequence[str] | None = None,
    dry_run: bool = False,
    allow_dirty: bool | None = None,
    env: Mapping[str, str] | None = None,
    runner: CommandRunner | None = None,
    evidence_path: Path | None = None,
    stop_on_failure: bool = True,
    python: str | None = None,
    verify_interpreter: bool = True,
) -> GateEvidence:
    """Run the immutable pinned-SHA release gate.

    Returns :class:`GateEvidence` for every outcome including refusals. Raises
    only for programmer errors (unknown phase names before pin). Dirty/moved
    HEAD become ``status="refused"`` evidence rather than uncaught exceptions
    at this layer so callers always get a durable record.
    """
    e = dict(env) if env is not None else dict(os.environ)
    root = (repo_root or default_repo_root()).resolve()
    if allow_dirty is None:
        allow_dirty = _truthy(e.get("RELEASE_GATE_ALLOW_DIRTY"))

    started = _utc_now()

    # Refuse certification if PYTEST_ADDOPTS is present in environment
    if (e.get("PYTEST_ADDOPTS") or "").strip():
        evidence = GateEvidence(
            pinned_sha="",
            status="refused",
            started_at=started,
            ended_at=_utc_now(),
            repo_root=str(root),
            allow_dirty=bool(allow_dirty),
            refuse_reason=(
                f"refusing certification: PYTEST_ADDOPTS={e['PYTEST_ADDOPTS']!r} is set in environment; "
                "pytest addopts poisoning can silently alter or deselect gate test suites"
            ),
            selected_phases=list(phases or []),
            interpreter_verified=False,
        )
        _maybe_write(evidence, evidence_path, root, e)
        return evidence

    # Resolve the audited project interpreter; refuse certification if not local.
    # Resolution is a path-shape check only, so the selected interpreter is then
    # *executed* and made to prove it is the project venv and can import the
    # gate's tooling. Skipped when a runner is injected: those callers replace
    # the whole subprocess world, so there is no real interpreter to interrogate.
    # A run that skipped verification is recorded as such and can never end in
    # ``passed`` — otherwise these two carve-outs would emit evidence identical
    # to a real certification, and the check would be optional in practice.
    #
    # ``interpreter_verified`` records what *happened*, not what was intended, so
    # it starts False and is set only once verification has actually returned. A
    # run that intended to verify but was refused by the check did not verify,
    # and its evidence must not claim otherwise.
    will_verify = runner is None and verify_interpreter
    interpreter_verified = False
    try:
        py = python or resolve_python(e, repo_root=root, require_project_local=True)
        if will_verify:
            verify_certification_interpreter(py, repo_root=root, require_local_prefix=True)
            interpreter_verified = True
    except InterpreterError as exc:
        evidence = GateEvidence(
            pinned_sha="",
            status="refused",
            started_at=started,
            ended_at=_utc_now(),
            repo_root=str(root),
            allow_dirty=bool(allow_dirty),
            refuse_reason=str(exc),
            selected_phases=list(phases or []),
            interpreter_verified=interpreter_verified,
        )
        _maybe_write(evidence, evidence_path, root, e)
        return evidence

    # Phase subprocesses run under the certification environment (REQUIRE_PG=1)
    # so PG-backed tests fail loudly instead of skipping into a false green.
    # run_phase applies it; an injected runner (tests) owns its own world.
    specs = default_phase_specs(python=py, repo_root=root)

    try:
        selected = select_phases(specs, only=phases, env=e)
    except ReleaseGateError as exc:
        evidence = GateEvidence(
            pinned_sha="",
            status="refused",
            started_at=started,
            ended_at=_utc_now(),
            repo_root=str(root),
            allow_dirty=bool(allow_dirty),
            refuse_reason=str(exc),
            selected_phases=list(phases or []),
            python=py,
            require_pg=True,
            interpreter_verified=interpreter_verified,
        )
        _maybe_write(evidence, evidence_path, root, e)
        return evidence

    # --- pin once ---------------------------------------------------------
    try:
        pinned_sha = git_rev_parse_head(root, runner=runner)
        assert_clean_and_pinned(root, pinned_sha, allow_dirty=bool(allow_dirty), runner=runner)
    except ReleaseGateError as exc:
        # Best-effort pin for the record even on dirty refuse.
        try:
            pinned_sha = git_rev_parse_head(root, runner=runner)
        except ReleaseGateError:
            pinned_sha = ""
        evidence = GateEvidence(
            pinned_sha=pinned_sha,
            status="refused",
            started_at=started,
            ended_at=_utc_now(),
            repo_root=str(root),
            allow_dirty=bool(allow_dirty),
            refuse_reason=str(exc),
            selected_phases=[s.name for s in selected],
            python=py,
            require_pg=True,
            interpreter_verified=interpreter_verified,
        )
        _maybe_write(evidence, evidence_path, root, e)
        return evidence

    evidence = GateEvidence(
        pinned_sha=pinned_sha,
        status="planned" if dry_run else "passed",
        started_at=started,
        repo_root=str(root),
        allow_dirty=bool(allow_dirty),
        selected_phases=[s.name for s in selected],
        python=py,
        require_pg=True,
        interpreter_verified=interpreter_verified,
    )

    for spec in selected:
        try:
            phase_ev = run_phase(
                spec,
                repo_root=root,
                pinned_sha=pinned_sha,
                allow_dirty=bool(allow_dirty),
                dry_run=dry_run,
                env=e,
                runner=runner,
            )
        except ReleaseGateError as exc:
            phase_ev = PhaseEvidence(
                name=spec.name,
                status="refused",
                pinned_sha=pinned_sha,
                head_sha_at_start=pinned_sha,
                head_sha_at_end="",
                started_at=_utc_now(),
                ended_at=_utc_now(),
                duration_ms=0,
                exit_code=None,
                command=list(spec.argv),
                detail=str(exc),
            )
        evidence.phases.append(phase_ev)

        if phase_ev.status == "refused":
            evidence.status = "refused"
            evidence.refuse_reason = phase_ev.detail
            break
        if phase_ev.status == "failed":
            evidence.status = "failed"
            if stop_on_failure:
                break

    # Final provenance check when we still claim a non-refused outcome.
    if evidence.status in {"passed", "planned", "failed"}:
        try:
            assert_clean_and_pinned(root, pinned_sha, allow_dirty=bool(allow_dirty), runner=runner)
        except ReleaseGateError as exc:
            evidence.status = "refused"
            evidence.refuse_reason = str(exc)

    # Dry-run stays planned only if nothing refused.
    if dry_run and evidence.status == "passed":
        evidence.status = "planned"

    # Full-gate green requires every selected non-skipped phase to pass, and
    # no skipped conditional phases when running the complete plan without an
    # explicit phase filter. Skips are recorded honestly; they do not count as
    # a certified full gate.
    if (
        not dry_run
        and evidence.status == "passed"
        and phases is None
        and any(p.status == "skipped" for p in evidence.phases)
    ):
        evidence.status = "failed"
        evidence.refuse_reason = (
            "full gate incomplete: one or more conditional phases were skipped; "
            "set RELEASE_GATE_LIVE=1 and RELEASE_GATE_LOAD=1 for certification"
        )

    # Last word: only a verified interpreter may produce a certification. An
    # injected runner never executed the real commands and an unverified one may
    # not be the audited environment, so neither has certified anything — and
    # evidence saying "passed" is exactly how that would go unnoticed. Applied
    # after every other transition so no later rule can reinstate ``passed``.
    # Failures and refusals keep their own status: a simulated failure is still
    # a failure, and softening it here would be the same defect inverted.
    if evidence.status == "passed" and not interpreter_verified:
        evidence.status = "simulated"
        evidence.refuse_reason = (
            "not a certification: the interpreter was not verified "
            "(injected runner or verification disabled)"
        )

    # Dirty-mode override check: RELEASE_GATE_ALLOW_DIRTY=1 allows local debugging, but can NEVER certify or return exit 0.
    if evidence.allow_dirty and evidence.status in {"passed", "planned"}:
        evidence.status = "simulated"
        evidence.refuse_reason = (
            "not a certification: RELEASE_GATE_ALLOW_DIRTY=1 was used on a dirty tree"
        )

    evidence.ended_at = _utc_now()
    _maybe_write(evidence, evidence_path, root, e)
    return evidence


def _write_or_refuse(evidence: GateEvidence, path: Path) -> None:
    """Write the record, translating an unusable location into a refusal.

    ``FileExistsError`` is deliberately *not* translated: it is the collision
    signal :func:`_maybe_write` acts on, and for an operator-named path it is
    the verdict itself. Every other ``OSError`` becomes an
    :class:`EvidenceWriteError` so the caller can report an evidence problem as
    such, rather than labelling any stray I/O failure that way.
    """
    try:
        write_evidence(evidence, path)
    except FileExistsError:
        raise
    except OSError as exc:
        raise EvidenceWriteError(f"cannot write evidence to {path}: {exc}") from exc


def _maybe_write(
    evidence: GateEvidence,
    evidence_path: Path | None,
    root: Path,
    env: Mapping[str, str],
) -> None:
    """Persist the record, retrying only names the gate generated itself.

    An operator-supplied ``--evidence`` path is written exactly once: silently
    picking a different filename because theirs already existed would hide the
    clobber it is meant to prevent. Auto-generated names may be regenerated,
    since a collision there is a naming accident rather than an instruction.
    """
    if evidence_path is not None:
        _write_or_refuse(evidence, evidence_path)
        return

    sha = evidence.pinned_sha or "refused"
    last: OSError | None = None
    for _ in range(_EVIDENCE_WRITE_ATTEMPTS):
        try:
            _write_or_refuse(evidence, evidence_path_for(root, sha, env))
            return
        except FileExistsError as exc:  # regenerate and try a fresh name
            last = exc
    raise EvidenceWriteError(
        f"could not create a unique evidence file after {_EVIDENCE_WRITE_ATTEMPTS} attempts: {last}"
    )


def format_summary(evidence: GateEvidence) -> str:
    """Human-readable one-screen summary."""
    lines = [
        "════════════════════════════════════════════════════════════",
        " OmniAgentOS release gate (H-30)",
        f" status:     {evidence.status}",
        f" pinned_sha: {evidence.pinned_sha or '(none)'}",
        f" repo:       {evidence.repo_root}",
        f" python:     {evidence.python or '(unresolved)'}",
        f" require_pg: {'1' if evidence.require_pg else '0'}",
        f" started:    {evidence.started_at}",
        f" ended:      {evidence.ended_at}",
    ]
    if evidence.allow_dirty:
        lines.append(" WARNING:    RELEASE_GATE_ALLOW_DIRTY=1 (not certifiable)")
    if evidence.refuse_reason:
        lines.append(f" refuse:     {evidence.refuse_reason}")
    lines.append(" phases:")
    if not evidence.phases:
        lines.append("   (none executed)")
    for p in evidence.phases:
        rc = "-" if p.exit_code is None else str(p.exit_code)
        lines.append(f"   [{p.status:8}] {p.name:18} rc={rc:4} {p.duration_ms}ms")
    lines.append("════════════════════════════════════════════════════════════")
    return "\n".join(lines)


def build_arg_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(
        prog="omniagentos.harnesses.release_gate",
        description="Immutable pinned-SHA release / convergence gate (H-30).",
    )
    p.add_argument(
        "--list",
        action="store_true",
        help="List named phases and exit without running them.",
    )
    p.add_argument(
        "--dry-run",
        action="store_true",
        help="Pin SHA, enforce clean tree, plan phases without executing them.",
    )
    p.add_argument(
        "--phases",
        default="",
        help="Comma-separated subset of phases (default: full gate).",
    )
    p.add_argument(
        "--repo-root",
        default="",
        help="Repository root (default: auto-detect).",
    )
    p.add_argument(
        "--evidence",
        default="",
        help="Path for evidence JSON (default: $OMNIAGENTOS_VAR_DIR/release-gate/).",
    )
    p.add_argument(
        "--allow-dirty",
        action="store_true",
        help="Debug only: allow dirty tree (evidence records the override).",
    )
    p.add_argument(
        "--continue-on-failure",
        action="store_true",
        help="Run remaining phases after a failure (default: stop on first fail).",
    )
    return p


def main(argv: Sequence[str] | None = None) -> int:
    args = build_arg_parser().parse_args(list(argv) if argv is not None else None)
    root = Path(args.repo_root).resolve() if args.repo_root else default_repo_root()

    # --list is informational only; does not require a certified interpreter.
    if args.list:
        try:
            py = resolve_python(repo_root=root, require_project_local=False)
        except InterpreterError:
            py = "python"  # fallback for display only
        specs = default_phase_specs(python=py, repo_root=root)
        for spec in specs:
            flag = " (conditional)" if spec.conditional else ""
            print(f"{spec.name:18}  {spec.description}{flag}")
        return 0

    only = [x.strip() for x in args.phases.split(",") if x.strip()] or None
    allow_dirty = bool(args.allow_dirty) or _truthy(os.environ.get("RELEASE_GATE_ALLOW_DIRTY"))
    # Interpreter resolution happens inside run_release_gate with proper validation.
    try:
        evidence = run_release_gate(
            repo_root=root,
            phases=only,
            dry_run=bool(args.dry_run),
            allow_dirty=allow_dirty,
            evidence_path=Path(args.evidence) if args.evidence else None,
            stop_on_failure=not bool(args.continue_on_failure),
        )
    except (EvidenceWriteError, FileExistsError) as exc:
        # An unrecordable verdict must refuse with a legible reason, not abort
        # with a traceback: the verdict is worthless unrecorded, and a crash
        # here is indistinguishable from a crashed gate. Only evidence errors
        # are caught — a stray I/O failure elsewhere must not be reported as
        # an evidence problem.
        print(f"release gate refused: cannot record evidence — {exc}", file=sys.stderr)
        return 3
    print(format_summary(evidence))
    if evidence.status in {"passed", "planned"}:
        return 0
    if evidence.status == "refused":
        return 3
    return 1


if __name__ == "__main__":
    raise SystemExit(main())
