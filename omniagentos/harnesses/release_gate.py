"""H-30 — immutable pinned-SHA release / convergence gate.

One orchestration entry point for the full release gate. Every run:

1. pins ``HEAD`` once at the start;
2. refuses a dirty worktree (uncommitted or untracked changes that would make
   the certified tree un-reproducible);
3. re-checks that ``HEAD`` has not moved and the tree is still clean before
   every named phase and after the last phase;
4. records per-phase evidence (command, exit code, duration, head sha, log
   excerpt) so certification claims can be audited later.

This module is the *orchestration* for H-30. Individual phase payloads
(OpenAPI generation, dependency upgrades, coverage policy, scale tests) may
be owned by satellite lanes; the gate only requires that each phase name is
present, ordered, and fail-closed.

Do not treat a curated subset (e.g. ``scripts/certify-omniagentos.sh``) as a
substitute for this gate. Curated suites are component probes; this gate is
the release signal.

Usage::

    python -m omniagentos.harnesses.release_gate --list
    python -m omniagentos.harnesses.release_gate --dry-run
    python -m omniagentos.harnesses.release_gate --phases ruff,format,mypy
    python -m omniagentos.harnesses.release_gate   # full gate (resource-heavy)

Environment:

    OMNIAGENTOS_PYTHON          Interpreter for phase commands (default: project
                                ``.venv/bin/python``; never a bare PATH python)
    OMNIAGENTOS_VAR_DIR         Evidence root (default: <repo>/var)
    RELEASE_GATE_ALLOW_DIRTY    Set to ``1`` only for local debugging — never
                                for certification. Evidence records the override.
    RELEASE_GATE_LIVE           Include live/restart phases (default: 1 for full)
    RELEASE_GATE_LOAD           Include load/contention phases (default: 1 for full)

The gate *exports* ``OMNIAGENTOS_REQUIRE_PG=1`` to every phase subprocess: a
certification run must not be able to go green because PostgreSQL-backed tests
skipped themselves. See :func:`certification_env`.
"""

